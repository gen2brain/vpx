#define BCAST16(name, val)             \
	DATA name+0(SB)/8, $val;       \
	DATA name+8(SB)/8, $val;       \
	GLOBL name(SB), RODATA|NOPTR, $16

BCAST16(upOne<>, 0x0101010101010101)
BCAST16(yuv19077<>, 0x4a854a854a854a85)
BCAST16(yuv26149<>, 0x6625662566256625)
BCAST16(yuv14234<>, 0x379a379a379a379a)
