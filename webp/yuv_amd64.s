BCAST16(yuvAlpha<>, 0xff000000ff000000)

// func upsample16SSE(top, cur, out *byte)
TEXT ·upsample16SSE(SB), NOSPLIT, $0-24
	MOVQ top+0(FP), SI
	MOVQ cur+8(FP), DX
	MOVQ out+16(FP), DI

	MOVOU (SI), X0
	MOVOU 1(SI), X1
	MOVOU (DX), X2
	MOVOU 1(DX), X3

	MOVO  X0, X4
	PAVGB X3, X4
	MOVO  X1, X5
	PAVGB X2, X5
	MOVO  X4, X6
	PXOR  X5, X6

	MOVO X0, X7
	PXOR X3, X7
	MOVO X1, X8
	PXOR X2, X8

	MOVO  X7, X9
	POR   X8, X9
	POR   X6, X9
	PAND  upOne<>(SB), X9
	MOVO  X4, X10
	PAVGB X5, X10
	PSUBB X9, X10

	MOVO  X10, X11
	PAVGB X5, X11
	MOVO  X8, X12
	PAND  X6, X12
	MOVO  X10, X13
	PXOR  X5, X13
	POR   X13, X12
	PAND  upOne<>(SB), X12
	PSUBB X12, X11

	MOVO  X10, X12
	PAVGB X4, X12
	MOVO  X7, X13
	PAND  X6, X13
	MOVO  X10, X14
	PXOR  X4, X14
	POR   X14, X13
	PAND  upOne<>(SB), X13
	PSUBB X13, X12

	MOVO      X0, X13
	PAVGB     X11, X13
	MOVO      X1, X14
	PAVGB     X12, X14
	MOVO      X13, X15
	PUNPCKLBW X14, X15
	PUNPCKHBW X14, X13
	MOVOU     X15, (DI)
	MOVOU     X13, 16(DI)

	MOVO      X2, X13
	PAVGB     X12, X13
	MOVO      X3, X14
	PAVGB     X11, X14
	MOVO      X13, X15
	PUNPCKLBW X14, X15
	PUNPCKHBW X14, X13
	MOVOU     X15, 32(DI)
	MOVOU     X13, 48(DI)

	RET

// func yuvToRGBA32SSE(dst, y, u, v *byte)
TEXT ·yuvToRGBA32SSE(SB), NOSPLIT, $0-32
	MOVQ dst+0(FP), DI
	MOVQ y+8(FP), SI
	MOVQ u+16(FP), DX
	MOVQ v+24(FP), BX

	MOVQ $4, CX

loop:
	PXOR      X7, X7
	MOVQ      (SI), X0
	PUNPCKLBW X0, X7
	PMULHUW   yuv19077<>(SB), X7

	PXOR      X1, X1
	MOVQ      (DX), X0
	PUNPCKLBW X0, X1

	PXOR      X2, X2
	MOVQ      (BX), X0
	PUNPCKLBW X0, X2

	MOVO    X2, X3
	PMULHUW yuv26149<>(SB), X3
	MOVO    X7, X6
	PSUBW   yuv14234<>(SB), X6
	PADDW   X6, X3
	PSRAW   $6, X3

	MOVO    X1, X4
	PMULHUW yuv6419<>(SB), X4
	MOVO    X2, X6
	PMULHUW yuv13320<>(SB), X6
	PADDW   X6, X4
	MOVO    X7, X6
	PADDW   yuv8708<>(SB), X6
	PSUBW   X4, X6
	PSRAW   $6, X6
	MOVO    X6, X4

	MOVO    X1, X5
	PMULHUW yuv33050<>(SB), X5
	PADDUSW X7, X5
	PSUBUSW yuv17685<>(SB), X5
	PSRLW   $6, X5

	PACKUSWB X5, X3
	PXOR     X6, X6
	PACKUSWB X6, X4

	MOVO      X3, X0
	PUNPCKLBW X4, X0
	PUNPCKHBW X4, X3
	MOVO      X0, X6
	PUNPCKLWL X3, X6
	PUNPCKHWL X3, X0

	MOVOU (DI), X1
	PAND  yuvAlpha<>(SB), X1
	POR   X1, X6
	MOVOU X6, (DI)

	MOVOU 16(DI), X1
	PAND  yuvAlpha<>(SB), X1
	POR   X1, X0
	MOVOU X0, 16(DI)

	ADDQ $8, SI
	ADDQ $8, DX
	ADDQ $8, BX
	ADDQ $32, DI
	DECQ CX
	JNZ  loop

	RET
