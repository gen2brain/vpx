// func sseSSE(a, b *byte, size int) int
TEXT ·sseSSE(SB), NOSPLIT, $0-32
	MOVQ a+0(FP), SI
	MOVQ b+8(FP), DI
	MOVQ size+16(FP), CX

	PXOR X0, X0
	PXOR X7, X7
	MOVQ CX, DX

	CMPQ CX, $16
	JE   loop16
	CMPQ CX, $8
	JE   loop8

loop4:
	MOVL      (SI), X1
	MOVL      (DI), X2
	PUNPCKLBW X7, X1
	PUNPCKLBW X7, X2
	PSUBW     X2, X1
	PMADDWL   X1, X1
	PADDD     X1, X0
	ADDQ      $32, SI
	ADDQ      $32, DI
	DECQ      DX
	JNZ       loop4
	JMP       done

loop8:
	MOVQ      (SI), X1
	MOVQ      (DI), X2
	PUNPCKLBW X7, X1
	PUNPCKLBW X7, X2
	PSUBW     X2, X1
	PMADDWL   X1, X1
	PADDD     X1, X0
	ADDQ      $32, SI
	ADDQ      $32, DI
	DECQ      DX
	JNZ       loop8
	JMP       done

loop16:
	MOVOU     (SI), X1
	MOVOU     (DI), X2
	MOVOU     X1, X3
	MOVOU     X2, X4
	PUNPCKLBW X7, X1
	PUNPCKHBW X7, X3
	PUNPCKLBW X7, X2
	PUNPCKHBW X7, X4
	PSUBW     X2, X1
	PSUBW     X4, X3
	PMADDWL   X1, X1
	PMADDWL   X3, X3
	PADDD     X1, X0
	PADDD     X3, X0
	ADDQ      $32, SI
	ADDQ      $32, DI
	DECQ      DX
	JNZ       loop16

done:
	MOVOU  X0, X1
	PSRLDQ $8, X1
	PADDD  X1, X0
	MOVOU  X0, X1
	PSRLDQ $4, X1
	PADDD  X1, X0
	MOVL   X0, AX
	MOVQ   AX, ret+24(FP)
	RET

