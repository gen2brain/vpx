TEXT ·sseAVX2(SB), NOSPLIT, $0-32
	MOVQ a+0(FP), SI
	MOVQ b+8(FP), DI
	MOVQ size+16(FP), CX

	VPXOR Y0, Y0, Y0

loop:
	VPMOVZXBW (SI), Y1
	VPMOVZXBW (DI), Y2
	VPSUBW    Y2, Y1, Y1
	VPMADDWD  Y1, Y1, Y1
	VPADDD    Y1, Y0, Y0
	ADDQ      $32, SI
	ADDQ      $32, DI
	DECQ      CX
	JNZ       loop

