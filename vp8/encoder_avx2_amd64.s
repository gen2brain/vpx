	VPADDD       X1, X0, X0
	VPSHUFD      $0x0e, X0, X1
	VPADDD       X1, X0, X0
	VPSHUFD      $0x01, X0, X1
	VPADDD       X1, X0, X0
	VMOVD        X0, AX
	MOVQ         AX, ret+24(FP)
	VZEROUPPER
	RET

