#define SMLALS(m, n, d)  WORD $(0x0E608000 | ((m) << 16) | ((n) << 5) | (d))
#define SMLALS2(m, n, d) WORD $(0x4E608000 | ((m) << 16) | ((n) << 5) | (d))

// func sseNEON(a, b *byte, size int) int
TEXT ·sseNEON(SB), NOSPLIT, $0-32
	MOVD a+0(FP), R0
	MOVD b+8(FP), R1
	MOVD size+16(FP), R2

	VMOVI $0, V0.B16
	MOVD  R2, R3

	CMP $16, R2
	BEQ loop16
	CMP $8, R2
	BEQ loop8

loop4:
	VLD1  (R0), V1.S[0]
	VLD1  (R1), V2.S[0]
	VUXTL V1.B8, V1.H8
	VUXTL V2.B8, V2.H8
	VSUB  V2.H8, V1.H8, V3.H8
	SMLALS(3, 3, 0)
	ADD   $32, R0
	ADD   $32, R1
	SUB   $1, R3
	CBNZ  R3, loop4
	B     done

loop8:
	VLD1  (R0), [V1.D1]
	VLD1  (R1), [V2.D1]
	VUXTL V1.B8, V1.H8
	VUXTL V2.B8, V2.H8
	VSUB  V2.H8, V1.H8, V3.H8
	SMLALS(3, 3, 0)
	SMLALS2(3, 3, 0)
	ADD   $32, R0
	ADD   $32, R1
	SUB   $1, R3
	CBNZ  R3, loop8
	B     done

loop16:
	VLD1   (R0), [V1.B16]
	VLD1   (R1), [V2.B16]
	VUXTL  V1.B8, V4.H8
	VUXTL  V2.B8, V5.H8
	VUXTL2 V1.B16, V6.H8
	VUXTL2 V2.B16, V7.H8
	VSUB   V5.H8, V4.H8, V3.H8
	SMLALS(3, 3, 0)
	SMLALS2(3, 3, 0)
	VSUB   V7.H8, V6.H8, V3.H8
	SMLALS(3, 3, 0)
	SMLALS2(3, 3, 0)
	ADD    $32, R0
	ADD    $32, R1
	SUB    $1, R3
	CBNZ   R3, loop16

done:
	VADDV V0.S4, V1
	VMOV  V1.S[0], R4
	MOVD  R4, ret+24(FP)
	RET

#define SSHRS(k, n, d) WORD $(0x4F000400 | ((64 - (k)) << 16) | ((n) << 5) | (d))
#define SSHRH(k, n, d) WORD $(0x0F000400 | ((32 - (k)) << 16) | ((n) << 5) | (d))
#define XTNH(n, d)     WORD $(0x0E612800 | ((n) << 5) | (d))
#define SMULLS(m, n, d) WORD $(0x0E60C000 | ((m) << 16) | ((n) << 5) | (d))

#define TRANSPOSE4(a, b, c, d, t0, t1, t2, t3) \
	VTRN1 b.H4, a.H4, t0.H4 \
	VTRN2 b.H4, a.H4, t1.H4 \
	VTRN1 d.H4, c.H4, t2.H4 \
	VTRN2 d.H4, c.H4, t3.H4 \
	VTRN1 t2.S2, t0.S2, a.S2 \
	VTRN2 t2.S2, t0.S2, c.S2 \
	VTRN1 t3.S2, t1.S2, b.S2 \
	VTRN2 t3.S2, t1.S2, d.S2

