TEXT ·transformDCSSE(SB), NOSPLIT, $0-16
	MOVQ in+0(FP), SI
	MOVQ dst+8(FP), DI

	MOVWQSX (SI), AX
	ADDQ  $4, AX
	MOVWQSX AX, AX
	SARQ  $3, AX

	MOVQ  AX, DX
	NEGQ  DX
	TESTQ AX, AX
	CMOVQLT DX, AX
	CMPQ  AX, $255
	JLE   small
	MOVQ  $255, AX

small:
	MOVQ  AX, X0
	PUNPCKLBW X0, X0
	PUNPCKLWL X0, X0
