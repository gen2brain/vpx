TEXT ·transformSSE(SB), NOSPLIT, $0-24
	MOVQ in+0(FP), SI
	MOVQ dst+8(FP), DI
	MOVQ two+16(FP), CX

	MOVQ (SI), X0
	MOVQ 8(SI), X1
	MOVQ 16(SI), X2
	MOVQ 24(SI), X3

	TESTQ CX, CX
	JZ    one

	MOVQ  32(SI), X4
	PUNPCKLQDQ X4, X0
	MOVQ  40(SI), X4
	PUNPCKLQDQ X4, X1
	MOVQ  48(SI), X4
	PUNPCKLQDQ X4, X2
	MOVQ  56(SI), X4
	PUNPCKLQDQ X4, X3

one:
	MOVOU kk1<>(SB), X12
	MOVOU kk2<>(SB), X13

	PASS
	TRANSPOSE

	PADDW kfour<>(SB), X0

	PASS

	PSRAW $3, X0
	PSRAW $3, X1
	PSRAW $3, X2
	PSRAW $3, X3

	TRANSPOSE

	PXOR X15, X15

	TESTQ CX, CX
	JZ    storeone

	MOVQ  (DI), X4
	PUNPCKLBW X15, X4
	PADDW X0, X4
	PACKUSWB X4, X4
	MOVQ  X4, (DI)

